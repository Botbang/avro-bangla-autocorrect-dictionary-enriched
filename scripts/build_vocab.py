def main() -> None:
    seen: set[str] = set()
    unique: list[tuple[str, str]] = []
    for key, value in ENTRIES:
        if key in seen:
            continue
        seen.add(key)
        unique.append((key, value))

    lines = [
        "# NSTU / academic Bangla vocabulary batch for Avro autocorrect",
        "# Format: <input_or_misspelling> <correct_avro_romanization>",
        "# Sources documented in README.md",
        "",
    ]
    lines.extend(f"{k} {v}" for k, v in unique)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(unique)} unique entries to {OUT}")


if __name__ == "__main__":
    main()
